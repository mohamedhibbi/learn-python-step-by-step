# Checking data types

print(type(1928))                  # Int
print(type(10.018))                # Float
print(type(1 + 3j))              # Complex
print(type('Mohamed'))          # String
print(type([8, 2, 3, 10]))           # List
print(type({'name': 'Mohamed'}))  # Dictionary
print(type({10.8, 2.4, 7.7}))    # Tuple
